"""Generate the FWDPORT variant list header and one instantiation TU per variant (kda-fwdport experiments).
kVar = SCHED*10000 + BNcode*1000 + DESC*100 + BASIS*10 + PV; BNcode 0:256 1:224 2:192 3:128."""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
VARS = [int(v) for v in open(os.path.join(HERE, "fwdport_variants.txt")).read().split()]
def main():
    with open(os.path.join(HERE, "fwdport_variants.h"), "w") as f:
        f.write("// generated by gen_fwdport.py\n#pragma once\n#define FWDPORT_LIST(X) " + " ".join(f"X({v})" for v in VARS) + "\n")
    for old in os.listdir(HERE):
        if old.startswith("flash_fwd_hdim128_fwdport_v") and old.endswith(".cu"):
            os.remove(os.path.join(HERE, old))
    for v in VARS:
        with open(os.path.join(HERE, f"flash_fwd_hdim128_fwdport_v{v}.cu"), "w") as f:
            f.write(f'// generated by gen_fwdport.py: FWDPORT variant {v}\n#include "dm_flagset.h"\n#include "flash_fwd_fp8port_launch.h"\n'
                    f"template void run_flash_fwd_fp8port_d128<{v}>(Flash_fwd_fp8_params &params, cudaStream_t stream);\n")
    return [f"flash_fwd_hdim128_fwdport_v{v}.cu" for v in VARS]
if __name__ == "__main__":
    print(main())
